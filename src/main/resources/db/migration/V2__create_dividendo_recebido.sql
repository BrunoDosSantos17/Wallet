CREATE TABLE dividendo_recebido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asset_position BIGINT NOT NULL REFERENCES asset_position(id),
    valor_dividendo NUMERIC(38, 8) NOT NULL CHECK (valor_dividendo >= 0),
    tipo_provento VARCHAR(30) NOT NULL CHECK (tipo_provento IN ('DIVIDENDO', 'JCP', 'RENDIMENTO_FII')),
    data_pagamento DATE NOT NULL,
    data_insercao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_update TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    identificador_origem VARCHAR(255),
    CONSTRAINT uk_dividendo_position_origem UNIQUE (id_asset_position, identificador_origem)
);

CREATE INDEX ix_dividendo_tipo_provento ON dividendo_recebido (tipo_provento);
