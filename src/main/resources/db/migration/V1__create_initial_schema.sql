CREATE TABLE wallet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255)
);

CREATE TABLE asset (
    ticker VARCHAR(255) PRIMARY KEY,
    name VARCHAR(255),
    type VARCHAR(255),
    current_price NUMERIC(38, 8),
    last_update TIMESTAMP(6)
);

CREATE TABLE asset_position (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    wallet_id BIGINT NOT NULL REFERENCES wallet(id),
    asset_ticker VARCHAR(255) NOT NULL REFERENCES asset(ticker),
    quantity NUMERIC(38, 12),
    average_price NUMERIC(38, 8),
    CONSTRAINT uk_asset_position_wallet_asset UNIQUE (wallet_id, asset_ticker)
);

CREATE TABLE "transaction" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id BIGINT REFERENCES wallet(id),
    asset_ticker VARCHAR(255) REFERENCES asset(ticker),
    type VARCHAR(255),
    quantity NUMERIC(38, 12),
    price NUMERIC(38, 8),
    date DATE,
    data_transaction DATE,
    import_identity VARCHAR(64)
);

CREATE UNIQUE INDEX uk_transaction_wallet_import_identity
    ON "transaction" (wallet_id, import_identity) WHERE import_identity IS NOT NULL;
CREATE INDEX ix_transaction_wallet_asset_history
    ON "transaction" (wallet_id, asset_ticker, data_transaction);
